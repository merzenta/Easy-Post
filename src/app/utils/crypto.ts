import crypto from 'crypto';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // 96-bit IV recommended for GCM

/**
 * Derives a consistent 32-byte (256-bit) encryption key from the environment secret.
 * Falls back to a deterministic development fallback key with a warning if not set.
 */
function getMasterKey(): Buffer {
  const secret = process.env.APP_ENCRYPTION_KEY || 'default-dev-secret-key-auspost-wix-2026';
  if (!process.env.APP_ENCRYPTION_KEY && process.env.NODE_ENV === 'production') {
    throw new Error('APP_ENCRYPTION_KEY environment variable is required in production.');
  }
  // SHA-256 hash ensures exactly 32 bytes regardless of secret encoding or length
  return crypto.createHash('sha256').update(secret).digest();
}

/**
 * Encrypts a sensitive credential string using AES-256-GCM with an authenticated tag.
 * Returns a serialized string in format: `ivHex:authTagHex:ciphertextHex`.
 */
export function encryptCredential(plainText: string): string {
  if (!plainText) return '';
  const key = getMasterKey();
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);

  let encrypted = cipher.update(plainText, 'utf8', 'hex');
  encrypted += cipher.final('hex');
  const authTag = cipher.getAuthTag().toString('hex');

  return `${iv.toString('hex')}:${authTag}:${encrypted}`;
}

/**
 * Decrypts an encrypted credential blob generated by `encryptCredential`.
 * Validates integrity via GCM authentication tag.
 */
export function decryptCredential(encryptedBlob: string): string {
  if (!encryptedBlob) return '';
  const parts = encryptedBlob.split(':');
  if (parts.length !== 3) {
    throw new Error('Invalid encrypted credential payload format.');
  }

  const [ivHex, authTagHex, encryptedHex] = parts;
  const key = getMasterKey();
  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');

  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
  decipher.setAuthTag(authTag);

  let decrypted = decipher.update(encryptedHex, 'hex', 'utf8');
  decrypted += decipher.final('utf8');

  return decrypted;
}

/**
 * Generates a cryptographically random 32-byte hex key for use as APP_ENCRYPTION_KEY.
 */
export function generateEncryptionKey(): string {
  return crypto.randomBytes(32).toString('hex');
}
